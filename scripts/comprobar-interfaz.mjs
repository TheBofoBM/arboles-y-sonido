import assert from 'node:assert/strict'

// La misma comprobación se ejecuta contra Vite y contra GitHub Pages.
export async function comprobarInterfaz(page, captura) {
  const checks = []
  await page.locator('.tree-svg').waitFor()
  assert.equal(await page.locator('.tree-node').count(), 5)
  assert.equal(await page.locator('table:visible, pre:visible').count(), 0)
  assert.equal(await page.locator('.entry-editor').getAttribute('open'), null)
  const colores = await page.locator('.tree-node').evaluateAll(ns => new Set(ns.map(n => getComputedStyle(n).getPropertyValue('--node-color'))).size)
  assert.equal(colores, 4)
  checks.push('Inicio con árbol de biblioteca visible, cuatro colores de operador y detalles técnicos cerrados')

  await page.evaluate(() => {
    window.recorridoObservado = []
    const svg = document.querySelector('.tree-svg')
    new MutationObserver(() => {
      const activo = svg.querySelector('[aria-current="step"]')
      if (activo && window.recorridoObservado.at(-1)?.id !== activo.dataset.nodeId) {
        window.recorridoObservado.push({ id: activo.dataset.nodeId, profundidad: Number(activo.dataset.depth) })
      }
    }).observe(svg, { subtree: true, attributes: true, attributeFilter: ['aria-current'] })
  })
  const player = page.getByRole('region', { name: 'Sampleos de árbol actual', exact: true })
  await player.getByRole('button', { name: 'Escuchar árbol actual', exact: true }).click()
  await page.locator('[aria-current="step"]').waitFor()
  assert.equal(await page.locator('[aria-current="step"]').getAttribute('data-depth'), '3')
  await page.locator('.listening-workspace').evaluate(el => window.scrollTo(0, el.getBoundingClientRect().top + scrollY - 24))
  await captura('arbol-escuchando')
  await page.waitForFunction(() => !document.querySelector('[aria-label="Sampleos de árbol actual"] button').disabled, null, { timeout: 12000 })
  const recorrido = await page.evaluate(() => window.recorridoObservado)
  assert.equal(recorrido.length, 5)
  assert.deepEqual(recorrido.map(n => n.profundidad), [3, 3, 2, 1, 0])
  assert.equal(await page.locator('.node-visited').count(), 5)
  assert.equal(await page.locator('[aria-current="step"]').count(), 0)
  assert.equal(await player.getByRole('progressbar').getAttribute('aria-valuenow'), '5')
  checks.push('Audio real en Chrome: postorden desde las relaciones, profundidades 3,3,2,1,0 y final completo con base')

  await player.getByText('Editar sonido · registro y base', { exact: true }).click()
  await player.getByLabel('Registro de la raíz').selectOption('5')
  await player.getByRole('button', { name: 'Escuchar árbol actual', exact: true }).click()
  await page.locator('[aria-current="step"]').waitFor()
  await page.waitForFunction(() => document.querySelector('.playback-line').innerText.includes('D4'))
  await player.getByRole('button', { name: 'Detener', exact: true }).click()
  assert.equal(await page.locator('[aria-current="step"]').count(), 0)
  await player.getByRole('button', { name: 'Restablecer sonido', exact: true }).click()
  checks.push('Registro editable: primer nodo D4 al elegir raíz G4; detener retira el resaltado; restablecer recupera G5')

  const sqlRef = page.locator('.sql-reference')
  await sqlRef.locator('summary').click()
  const sqlOriginal = await sqlRef.getByRole('textbox').inputValue()
  assert.match(sqlOriginal, /SELECT DISTINCT/)
  await sqlRef.getByRole('textbox').fill(sqlOriginal.replace('2020', '2024'))
  await sqlRef.getByRole('button', { name: 'Aplicar SQL al árbol' }).click()
  await page.getByText('Árbol actualizado desde el SQL editado.', { exact: true }).waitFor()
  await page.locator('[data-node-type="SELECCION"]').click()
  assert.match(await page.locator('.node-inspector').innerText(), /2024/)
  await page.getByRole('button', { name: 'Cerrar detalle del nodo' }).click()
  await sqlRef.getByRole('textbox').fill(sqlOriginal)
  await sqlRef.getByRole('button', { name: 'Aplicar SQL al árbol' }).click()
  await sqlRef.locator('summary').click()
  checks.push('Álgebra a SQL de referencia editable: cambiar el año actualiza el árbol y recuperar el SQL conserva el ejemplo')

  await page.locator('[data-node-type="SELECCION"]').click()
  assert.match(await page.locator('.node-inspector').innerText(), /L.anio > 2020 AND A.pais = 'México'/)
  await page.getByRole('button', { name: 'Cerrar detalle del nodo' }).click()
  const ancho = await page.locator('.tree-svg').getAttribute('width')
  await page.getByRole('button', { name: 'Acercar árbol' }).click()
  assert(Number(await page.locator('.tree-svg').getAttribute('width')) > Number(ancho))
  await page.getByRole('button', { name: 'Ajustar', exact: true }).click()
  const relacion = page.locator('[data-node-type="RELACION"]').first()
  await relacion.focus(); await page.keyboard.press('Enter')
  await page.locator('.node-inspector').waitFor()
  checks.push('Zoom, ajuste, detalle del predicado completo y selección de nodos por teclado')

  await page.getByRole('button', { name: 'JSON', exact: true }).click()
  await page.getByRole('button', { name: 'Procesar JSON', exact: true }).click()
  assert.equal(await page.locator('.tree-node').count(), 3)
  checks.push('Entrada JSON conservada: genera diagrama de tres nodos')
  await page.getByRole('button', { name: 'SQL', exact: true }).click()
  await page.getByRole('button', { name: 'Generar árbol desde SQL', exact: true }).click()
  await page.getByRole('button', { name: 'Aplicar reglas disponibles' }).click()
  await page.getByText('Historial: 3 transformaciones', { exact: true }).waitFor()
  assert.equal(await page.locator('.tree-node').count(), 6)
  await page.getByRole('button', { name: 'Deshacer paso', exact: true }).click()
  await page.getByText('Historial: 2 transformaciones', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Aplicar siguiente regla' }).click()
  checks.push('SQL y reglas heurísticas: tres pasos, seis nodos y deshacer')
  await page.getByRole('button', { name: 'Comparar original y actual' }).click()
  await page.getByRole('heading', { name: 'Equivalencia reconocida', exact: true }).waitFor()
  assert.equal(await page.locator('#tipo-a').inputValue(), 'json')
  assert.equal(await page.locator('#tipo-b').inputValue(), 'json')
  checks.push('Transferencia del original y la transformación a comparación A/B')

  await page.getByRole('button', { name: 'Cargar par equivalente de biblioteca' }).click()
  assert.equal(await page.locator('[aria-label="Resultado A"] .tree-node').count(), 5)
  assert.equal(await page.locator('[aria-label="Resultado B"] .tree-node').count(), 6)
  await page.getByRole('checkbox', { name: 'Ver árboles transformados' }).check()
  assert.equal(await page.locator('[aria-label="Resultado A"] .tree-node').count(), 6)
  const a = page.getByRole('region', { name: 'Sampleos de A', exact: true })
  const b = page.getByRole('region', { name: 'Sampleos de B', exact: true })
  await a.getByText('Editar sonido · registro y base', { exact: true }).click()
  await b.getByText('Editar sonido · registro y base', { exact: true }).click()
  await a.getByLabel('Registro de la raíz').selectOption('5')
  assert.equal(await b.getByLabel('Registro de la raíz').inputValue(), '5')
  await a.getByRole('button', { name: 'Restablecer sonido', exact: true }).click()
  await a.getByText('Editar sonido · registro y base', { exact: true }).click()
  await b.getByText('Editar sonido · registro y base', { exact: true }).click()
  checks.push('La comparación A/B comparte el mismo mapeo de registro y base')
  await a.getByRole('button', { name: 'Escuchar A', exact: true }).click()
  await page.locator('[aria-label="Resultado A"] [aria-current="step"]').waitFor()
  await b.getByRole('button', { name: 'Escuchar B', exact: true }).click()
  await page.locator('[aria-label="Resultado B"] [aria-current="step"]').waitFor()
  assert(await a.getByRole('button', { name: 'Escuchar A', exact: true }).isEnabled())
  await page.locator('.section-heading').evaluate(el => window.scrollTo(0, el.getBoundingClientRect().top + scrollY - 24))
  await captura('comparacion-visual')
  await page.waitForFunction(() => !document.querySelector('[aria-label="Sampleos de B"] button').disabled, null, { timeout: 12000 })
  assert.equal(await page.locator('[aria-label="Resultado B"] .node-visited').count(), 6)
  checks.push('Dos diagramas A/B; originales y transformados; B detiene A y termina sus seis nodos')

  await page.getByRole('button', { name: 'Álgebra relacional', exact: true }).click()
  await page.locator('.entry-editor > summary').click()
  await page.locator('#algebra-input').fill('PI[*](Libro)')
  await page.getByRole('button', { name: 'Generar árbol', exact: true }).click()
  await page.getByRole('alert').waitFor()
  assert.equal(await page.locator('.tree-node').count(), 0)
  checks.push('Álgebra inválida: mensaje legible y retirada del diagrama anterior')
  await page.getByRole('button', { name: 'Cargar biblioteca', exact: true }).click()
  await page.getByRole('button', { name: 'Generar árbol', exact: true }).click()
  assert.equal(await page.locator('.tree-node').count(), 5)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.tree-svg').waitFor()
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.locator('.listening-workspace').evaluate(el => window.scrollTo(0, el.getBoundingClientRect().top + scrollY - 12))
  await captura('arbol-movil')

  await page.getByRole('button', { name: 'Comparar A / B', exact: true }).click()
  await page.locator('.entry-editor > summary').click()
  const beforeB = await page.locator('#texto-b').inputValue()
  await page.locator('#texto-a').fill('SELECT * FROM Libro')
  assert.equal(await page.locator('.results-columns').count(), 0)
  await page.getByRole('button', { name: 'Generar y comparar árboles' }).click()
  await page.getByRole('alert').waitFor()
  assert.equal(await page.locator('#texto-b').inputValue(), beforeB)
  checks.push('Comparación: editar invalida los diagramas y modificar A conserva B')
  await page.getByRole('button', { name: 'Cargar par equivalente de biblioteca' }).click()
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.locator('.comparison-options').evaluate(el => window.scrollTo(0, el.getBoundingClientRect().top + scrollY - 12))
  await captura('comparacion-movil', true)
  checks.push('Móvil de 390 px: árboles y comparación sin desbordamiento de página')
  return { checks, recorrido }
}
